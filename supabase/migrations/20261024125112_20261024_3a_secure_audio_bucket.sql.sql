/*
# Phase 3: Secure Audio with Signed URLs

## Summary
Locks down the `vinyl-audio` storage bucket so audio files are no longer publicly
readable. The bucket's SELECT policy is changed from `public` to `authenticated`
only, ensuring that only logged-in users can access audio via signed URLs.

## Policy Changes
- `audio_read` on storage.objects: changed from `TO public` to `TO authenticated`
  so anonymous access is blocked. Signed URLs generated by the Supabase client
  (which include the user's JWT) will work; direct public URLs will not.

## Note
The Supabase storage RLS policies live on the `storage.objects` table. We
DROP and recreate the `audio_read` policy. The bucket itself (`vinyl-audio`)
already exists and is configured as a private bucket in practice once the
public SELECT policy is removed.
*/

-- Remove the public read policy on vinyl-audio bucket
DROP POLICY IF EXISTS "audio_read" ON storage.objects;

-- Create new policy: only authenticated users can read audio
CREATE POLICY "audio_read"
ON storage.objects FOR SELECT
TO authenticated
USING (bucket_id = 'vinyl-audio');
